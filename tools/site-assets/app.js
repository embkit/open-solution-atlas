/* Solution Atlas — the catalog's search and facets, and the chapter contents
   rail.

   Both modules are progressive enhancement. Without JS the catalog's card grid
   is already rendered and every contents link still works; the rail only gains
   a mark for the section being read.

   The search index (~800 KB) is NOT fetched on page load: it is loaded lazily
   on first search interaction, so visitors who only browse or use the facet
   filters never pay for it.

   Every string this module writes comes from the site's string catalog through
   `window.OSA_I18N` (assets/i18n.js, generated by tools/i18n.py), because the
   reader may switch language after these strings have been written. The
   catalog re-renders itself when that happens. */

(function () {
  "use strict";

  function tr(key, vars) {
    return window.OSA_I18N ? window.OSA_I18N.t(key, vars) : key;
  }

  var q = document.getElementById("q");
  var cards = document.getElementById("cards");
  var hits = document.getElementById("hits");
  var count = document.getElementById("count");
  var clearBtn = document.getElementById("clear");
  var emptyBtn = document.getElementById("empty-clear");
  var empty = document.getElementById("empty");
  var status = document.getElementById("index-status");
  if (!q || !cards) return;

  var cardEls = Array.prototype.slice.call(cards.querySelectorAll(".card"));
  var totalPacks = cardEls.length;
  var active = { domain: new Set(), maturity: new Set(), verification: new Set() };
  var fuse = null;
  var index = null;
  var indexLoading = null;
  var emptyEl = null;

  function setStatus(message) {
    if (!status) return;
    if (!message) {
      status.textContent = "";
      status.hidden = true;
      return;
    }
    status.textContent = message;
    status.hidden = false;
  }

  // ---- search index: loaded lazily, exactly once -------------------------
  function loadIndex() {
    if (index || indexLoading) return indexLoading || Promise.resolve();
    if (typeof Fuse === "undefined") {
      setStatus(tr("catalog.search.fail"));
      return Promise.resolve();
    }
    setStatus(tr("catalog.search.loading"));
    indexLoading = fetch("search-index.json")
      .then(function (r) {
        if (!r.ok) throw new Error("HTTP " + r.status);
        return r.json();
      })
      .then(function (data) {
        index = data;
        fuse = new Fuse(data, {
          includeScore: true,
          includeMatches: true,
          ignoreLocation: true,
          threshold: 0.34,
          minMatchCharLength: 2,
          keys: [
            { name: "t", weight: 0.42 },
            { name: "z", weight: 0.2 },
            { name: "g", weight: 0.16 },
            { name: "n", weight: 0.12 },
            { name: "x", weight: 0.1 }
          ]
        });
        setStatus("");
      })
      .catch(function () {
        setStatus(tr("catalog.search.index_fail"));
      });
    return indexLoading;
  }

  // ---- facets -----------------------------------------------------------
  document.querySelectorAll(".chip").forEach(function (chip) {
    chip.setAttribute("aria-pressed", "false");
    chip.addEventListener("click", function () {
      var facet = chip.getAttribute("data-facet");
      var value = chip.getAttribute("data-value");
      var set = active[facet];
      if (!set) return;
      if (set.has(value)) set.delete(value);
      else set.add(value);
      chip.setAttribute("aria-pressed", set.has(value) ? "true" : "false");
      render();
    });
  });

  function resetFilters() {
    Object.keys(active).forEach(function (k) { active[k].clear(); });
    document.querySelectorAll('.chip[aria-pressed="true"]').forEach(function (c) {
      c.setAttribute("aria-pressed", "false");
    });
    if (q) q.value = "";
    render();
  }

  if (emptyBtn) emptyBtn.addEventListener("click", resetFilters);

  if (clearBtn) {
    clearBtn.addEventListener("click", function () {
      Object.keys(active).forEach(function (k) { active[k].clear(); });
      document.querySelectorAll('.chip[aria-pressed="true"]').forEach(function (c) {
        c.setAttribute("aria-pressed", "false");
      });
      q.value = "";
      render();
    });
  }

  // ---- input ------------------------------------------------------------
  q.addEventListener("input", function () {
    render();
    if (q.value.trim()) loadIndex();
  });
  q.addEventListener("focus", function () {
    // Warm the index once the visitor shows search intent; do not block the
    // very first render on the network.
    if (q.value.trim()) loadIndex();
  });

  document.addEventListener("keydown", function (e) {
    if (e.key === "/" && document.activeElement !== q) {
      e.preventDefault();
      q.focus();
    } else if (e.key === "Escape" && document.activeElement === q) {
      q.value = "";
      render();
      q.blur();
    }
  });

  function facetActive() {
    return Object.keys(active).some(function (k) { return active[k].size > 0; });
  }

  function matchesActive(rec) {
    if (active.domain.size && !active.domain.has(rec.d)) return false;
    if (active.maturity.size && !active.maturity.has(rec.m)) return false;
    if (active.verification.size && !active.verification.has(rec.v)) return false;
    return true;
  }

  function cardMatches(el) {
    if (active.domain.size && !active.domain.has(el.getAttribute("data-domain"))) return false;
    if (active.maturity.size && !active.maturity.has(el.getAttribute("data-maturity"))) return false;
    if (active.verification.size && !active.verification.has(el.getAttribute("data-verification"))) return false;
    return true;
  }

  // ---- render -----------------------------------------------------------
  function render() {
    var query = q.value.trim();
    if (clearBtn) clearBtn.hidden = !(query || facetActive());

    if (query && fuse) {
      showHits(query);
    } else if (query && !index) {
      // Query typed, index not ready yet (or permanently unavailable).
      cards.hidden = true;
      hits.hidden = false;
      hits.innerHTML = "";
      if (count) count.textContent = "";
      var waiting = document.createElement("p");
      waiting.className = "count";
      waiting.textContent = indexLoading
        ? tr("catalog.search.waiting")
        : tr("catalog.search.waiting_fail");
      hits.appendChild(waiting);
    } else {
      showCards(query);
    }
  }

  function showCards(query) {
    cards.hidden = false;
    hits.hidden = true;
    var visible = 0;
    cardEls.forEach(function (el) {
      var ok = cardMatches(el);
      el.hidden = !ok;
      if (ok) visible++;
    });
    paintCount(visible);
    toggleEmpty(cards, visible === 0, tr("catalog.empty.title"));
  }

  /* The count keeps its structure — a <b> for the number, a `data-i18n` span
     for the word after it — because `.count b` is styled for tabular figures
     and the server renders it the same way for readers with JS off. The
     "n of m" reading has no such shape, so it is one localized sentence. */
  function paintCount(visible) {
    if (!count) return;
    var b = count.querySelector("b");
    var word = count.querySelector("[data-i18n]");
    if (visible === totalPacks) {
      if (b) b.textContent = String(visible);
      if (word) word.textContent = tr("word.pack");
      return;
    }
    count.textContent = tr("catalog.count.some", { n: visible, total: totalPacks });
  }

  function showHits(query) {
    var results = fuse.search(query, { limit: 60 });
    var filtered = results.filter(function (r) { return matchesActive(r.item); });
    cards.hidden = true;
    hits.hidden = false;
    if (count) {
      count.textContent = tr("catalog.hits.count", {
        n: filtered.length,
        word: tr(filtered.length === 1 ? "word.result.one" : "word.result"),
        q: query
      });
    }
    hits.innerHTML = "";
    filtered.forEach(function (r) { hits.appendChild(hitNode(r.item, query)); });
    toggleEmpty(hits, filtered.length === 0,
                tr("catalog.hits.empty", { q: query }));
  }

  function hitNode(rec, query) {
    var kind = tr(rec.k === "pack" ? "hit.kind.pack"
                   : rec.k === "doc" ? "hit.kind.doc" : "hit.kind.other");
    var path = rec.p ? rec.d + " / " + rec.p : rec.d;
    var a = document.createElement("a");
    a.className = "hit";
    a.href = rec.u;
    var top = document.createElement("div");
    top.className = "hit-top";
    var title = document.createElement("span");
    title.className = "hit-title";
    title.innerHTML = highlight(rec.t, query);
    var k = document.createElement("span");
    k.className = "hit-kind";
    k.textContent = kind + (path ? " · " + path : "");
    top.appendChild(title);
    top.appendChild(k);
    a.appendChild(top);
    var snip = snippet(rec.x, query);
    if (snip) {
      var p = document.createElement("p");
      p.className = "hit-snip";
      p.innerHTML = highlight(snip, query);
      a.appendChild(p);
    }
    return a;
  }

  function snippet(text, query) {
    if (!text) return "";
    var lower = text.toLowerCase();
    var needle = query.toLowerCase().split(/\s+/)[0];
    var at = lower.indexOf(needle);
    if (at < 0) return text.slice(0, 180) + (text.length > 180 ? "…" : "");
    var start = Math.max(0, at - 70);
    var end = Math.min(text.length, at + 140);
    return (start > 0 ? "…" : "") + text.slice(start, end).trim() + (end < text.length ? "…" : "");
  }

  function esc(s) {
    return s.replace(/[&<>"]/g, function (c) {
      return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c];
    });
  }

  function highlight(text, query) {
    var safe = esc(text);
    var terms = query.split(/\s+/).filter(function (t) { return t.length > 1; });
    if (!terms.length) return safe;
    var pattern = terms
      .map(function (t) { return t.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"); })
      .join("|");
    try {
      return safe.replace(new RegExp("(" + pattern + ")", "gi"), "<mark>$1</mark>");
    } catch (e) {
      return safe;
    }
  }

  function toggleEmpty(container, show, message) {
    if (show) {
      if (!emptyEl || emptyEl.parentNode !== container) {
        emptyEl = document.createElement("p");
        emptyEl.className = "count";
        container.appendChild(emptyEl);
      }
      emptyEl.textContent = message;
      emptyEl.hidden = false;
    } else if (emptyEl) {
      emptyEl.hidden = true;
    }
  }

  // The reader may switch language after these strings are on screen; the
  // catalog re-renders itself so the count, the empty states and the search
  // notices all follow the switch.
  document.addEventListener("osalocalechange", function () {
    render();
  });

  render();
})();

/* The contents rail. Reading position is the last heading that has passed
   under the sticky titlebar, which is the section a reader is in; the mark is
   `aria-current="location"`, the token ARIA defines for a position within a
   page. Recalculated on scroll, coalesced into one frame. */
(function () {
  "use strict";

  var toc = document.querySelector(".toc");
  if (!toc) return;
  var links = Array.prototype.slice.call(toc.querySelectorAll('a[href^="#"]'));
  if (!links.length) return;

  var items = [];
  links.forEach(function (a) {
    var id = a.getAttribute("href").slice(1);
    var el = document.getElementById(id);
    if (el) items.push({ el: el, a: a });
  });
  if (!items.length) return;

  var bar = document.querySelector(".titlebar");
  var line = (bar ? bar.offsetHeight : 0) + 16;
  var current = null;

  function mark(a) {
    if (a === current) return;
    if (current) current.removeAttribute("aria-current");
    if (a) a.setAttribute("aria-current", "location");
    current = a;
  }

  function update() {
    // The rail is `display: none` below 900px (the stylesheet owns that
    // breakpoint), so ask the DOM rather than repeating the width here: nothing
    // is marked when nothing is rendered, and a resize into the desktop layout
    // starts working because the elements were never abandoned.
    if (toc.offsetParent === null) return;
    var pick = items[0];
    for (var i = 0; i < items.length; i++) {
      if (items[i].el.getBoundingClientRect().top <= line) pick = items[i];
    }
    // At the foot of the page the last heading may never reach the line, so the
    // end of the scroll means the end of the document, not silence.
    var doc = document.documentElement;
    if (window.innerHeight + window.scrollY >= doc.scrollHeight - 4) {
      pick = items[items.length - 1];
    }
    mark(pick.a);
  }

  var queued = false;
  function onScroll() {
    if (queued) return;
    queued = true;
    window.requestAnimationFrame(function () { queued = false; update(); });
  }

  window.addEventListener("scroll", onScroll, { passive: true });
  window.addEventListener("resize", onScroll);
  update();
})();
